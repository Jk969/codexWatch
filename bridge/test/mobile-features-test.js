test('分片校验、文件名隔离、图片识别和会话归属', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cw-attachment-test-'));
  assert.equal(path.dirname(root),path.resolve(os.tmpdir()));
  try {
    const uploads = new Attachments(root);
    assert.throws(() => uploads.begin({ name:'huge', size:21*1024*1024 }), /20 MB/);
    const {id} = uploads.begin({ name:'../../图片.png', size:png.length, chatId:'chat-a' });
    assert.throws(()=>uploads.chunk({id,index:1,data:png.toString('base64')}),/顺序/);
    assert.throws(()=>uploads.finish({id}),/完整/);
    uploads.chunk({id,index:0,data:png.toString('base64')});
    assert.equal(uploads.finish({id}).image,true);
    assert.throws(()=>uploads.resolve([id],'chat-b'),/会话/);
    const [file] = uploads.resolve([id],'chat-a');
    assert.equal(path.dirname(file.path),root);
    assert.deepEqual(fs.readFileSync(file.path),png);
    const large=Buffer.alloc(150000,42);
    const other=uploads.begin({name:'中文报告.txt',size:large.length,chatId:'chat-a'});
    for(let offset=0,index=0;offset<large.length;offset+=65536,index++)uploads.chunk({id:other.id,index,data:large.subarray(offset,offset+65536).toString('base64')});
    assert.equal(uploads.finish({id:other.id}).image,false);
    assert.deepEqual(fs.readFileSync(uploads.resolve([other.id],'chat-a')[0].path),large);
  } finally { fs.rmSync(root,{recursive:true,force:true}); }
});

